/**
 * One-shot migration: packages.html → packages-data.ts
 *
 * The old template was 2,300 lines of hand-maintained markup — 33 packages,
 * each repeating the same structure, several of them mis-nested (one card had
 * its whole itinerary inside the <div class="package-meta"> meant for the price
 * badge). Parsing it into data lets the new template render one card shape for
 * every package, and makes the content editable without touching layout.
 *
 * Run once:  node scripts/extract-packages.mjs
 * Kept in the repo as the record of where packages-data.ts came from.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';

const html = readFileSync('src/app/pages/packages/packages.html', 'utf8');
const { document } = new JSDOM(`<body>${html}</body>`).window;

const text = el => (el?.textContent ?? '').replace(/\s+/g, ' ').trim();

/** Strips the decorative ❖ / bullet glyphs the old list items were typed with. */
const clean = s => text(s).replace(/^[❖•·▪◆*\-–—]\s*/, '').trim();

const slug = s =>
  s.toLowerCase().replace(/&/g, ' and ').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const packages = [...document.querySelectorAll('.package-card')].map(card => {
  const title = text(card.querySelector('.package-title'));
  const img = card.querySelector('img');

  // Queried from the card root, not from .package-header — the mis-nested
  // cards put these somewhere else in the subtree.
  const days = [...card.querySelectorAll('.day-plan')].map(d => ({
    title: text(d.querySelector('h6, h5')),
    body: text(d.querySelector('p')),
  })).filter(d => d.title || d.body);

  const listOf = sel => [...card.querySelectorAll(`${sel} li`)].map(clean).filter(Boolean);

  return {
    slug: slug(title),
    title,
    duration: text(card.querySelector('.duration')),
    price: text(card.querySelector('.price')),
    subtitle: text(card.querySelector('.package-details h4')),
    summary: text(card.querySelector('.package-details > p')),
    image: img
      ? {
          src: img.getAttribute('src') ?? '',
          srcset: img.getAttribute('srcset') ?? '',
          width: Number(img.getAttribute('width')) || 0,
          height: Number(img.getAttribute('height')) || 0,
          alt: img.getAttribute('alt') ?? title,
        }
      : null,
    highlights: listOf('.package-highlights'),
    days,
    includes: listOf('.service-inclusions'),
    excludes: listOf('.service-exclusions'),
  };
});

// Categories come from the old .category-card links, which already mapped a
// label + icon to each tour route.
const categories = [...document.querySelectorAll('.category-card')].map(a => ({
  slug: (a.getAttribute('routerLink') ?? '').replace(/^\//, ''),
  title: text(a.querySelector('h3')),
  blurb: text(a.querySelector('.category-description p')),
  icon: a.querySelector('app-icon')?.getAttribute('name') ?? 'compass',
}));

const ts = `// GENERATED by scripts/extract-packages.mjs from the previous packages.html.
// Edit this file to change package copy; the template renders whatever is here.

export interface PackageImage {
  src: string;
  srcset: string;
  width: number;
  height: number;
  alt: string;
}

export interface ItineraryDay {
  title: string;
  body: string;
}

export interface TourPackage {
  slug: string;
  title: string;
  duration: string;
  price: string;
  subtitle: string;
  summary: string;
  image: PackageImage | null;
  highlights: string[];
  days: ItineraryDay[];
  includes: string[];
  excludes: string[];
}

export interface PackageCategory {
  slug: string;
  title: string;
  blurb: string;
  icon: string;
}

export const CATEGORIES: PackageCategory[] = ${JSON.stringify(categories, null, 2)};

export const PACKAGES: TourPackage[] = ${JSON.stringify(packages, null, 2)};
`;

writeFileSync('src/app/pages/packages/packages-data.ts', ts);

